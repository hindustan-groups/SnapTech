/**
 * Ensures initial blog posts exist in whatever database is active (Neon / PostgreSQL).
 * Safe and idempotent: only inserts posts that do not already exist by id or slug.
 */
export async function autoSeedBlogPosts(prisma) {
  try {
    let seeded = 0
    for (const post of INITIAL_BLOG_POSTS) {
      const existing = await prisma.blogPost.findFirst({
        where: {
          OR: [{ id: post.id }, { slug: post.slug }],
        },
      })
      if (!existing) {
        await prisma.blogPost.create({ data: post })
        seeded++
      }
    }
    if (seeded > 0) {
      logger.info(`[BlogAutoSeed] Successfully seeded ${seeded} initial blog post(s) into database.`)
    }
  } catch (err) {
    logger.warn('[BlogAutoSeed] Non-fatal blog post auto-seed notice:', err.message)
  }
}
