async function seed() {
  console.log('Seeding Pricing Packages...')
  const count = await prisma.pricingPackage.count()
  if (count > 0) {
    console.log(`Database already has ${count} pricing packages. Skipping to avoid overwrite.`)
    process.exit(0)
  }

  for (const pkg of PACKAGES) {
    await prisma.pricingPackage.create({ data: pkg })
  }

  console.log(`Successfully seeded ${PACKAGES.length} pricing packages into PostgreSQL!`)
  process.exit(0)
}

seed().catch((err) => {
  console.error('Failed to seed pricing packages:', err)
  process.exit(1)
})
